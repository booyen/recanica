#!/usr/bin/env node
/**
 * Rekanica token build.
 * Source of truth: tokens/*.json (W3C Design Tokens format).
 * Output: generated/ — CSS, Tailwind v4 theme, Tailwind v3 preset, JS/TS, JSON,
 *         Flutter, SwiftUI, Jetpack Compose, Tokens Studio (Figma).
 *
 *   node scripts/build.mjs          write outputs
 *   node scripts/build.mjs --check  fail if outputs are out of date (CI)
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const root = join(import.meta.dirname, "..");
const out = join(root, "generated");
const CHECK = process.argv.includes("--check");
const HEADER = "GENERATED by @rekanica/tokens (scripts/build.mjs) from tokens/*.json. Do not edit.";

/* ---------- load ---------- */
const files = readdirSync(join(root, "tokens")).filter((f) => f.endsWith(".json")).sort();
const T = Object.assign({}, ...files.map((f) => JSON.parse(readFileSync(join(root, "tokens", f), "utf8"))));
const ext = (t) => t?.$extensions?.["com.rekanica"] ?? {};
const get = (path) => path.split(".").reduce((o, k) => o?.[k], T);
const refPath = (v) => (typeof v === "string" && /^\{.+\}$/.test(v) ? v.slice(1, -1) : null);
const resolve = (v) => { const p = refPath(v); return p ? resolve(get(p).$value) : v; };

/* ---------- colors ---------- */
const primitives = Object.entries(T.rk).flatMap(([fam, steps]) =>
  Object.entries(steps).map(([step, t]) => ({ name: `rk-${fam}-${step}`, key: `${fam}-${step}`, hex: t.$value, oklch: ext(t).oklch }))
);
const semantic = Object.entries(T.color).map(([name, t]) => {
  const darkRef = ext(t).dark ?? t.$value;
  return { name, lightRef: t.$value, darkRef, light: resolve(t.$value), dark: resolve(darkRef), hasDark: !!ext(t).dark };
});
const cssRef = (v) => { const p = refPath(v); return p ? `var(--${p.replace(/\./g, "-")})` : v; };
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^./, (c) => c.toUpperCase());
const px = (v) => parseFloat(v);
const rem = (v) => `${+(px(v) / 16).toFixed(4)}rem`;

/* ---------- scales ---------- */
const radius = Object.entries(T.radius).map(([k, t]) => ({ k, px: px(t.$value), css: ext(t).css ?? t.$value }));
const spacing = Object.entries(T.spacing).map(([k, t]) => ({ k, px: px(t.$value), css: ext(t).css ?? t.$value, desc: t.$description }));
const containers = Object.entries(T.container).map(([k, t]) => ({ k, px: px(t.$value), css: ext(t).css ?? t.$value }));
const text = Object.entries(T.text).map(([k, t]) => ({ k, size: px(t.$value.fontSize), lh: t.$value.lineHeight, ls: t.$value.letterSpacing ? parseFloat(t.$value.letterSpacing) : 0 }));
const weights = Object.fromEntries(Object.entries(T.font.weight).map(([k, t]) => [k, t.$value]));
const fonts = Object.fromEntries(Object.entries(T.font.family).map(([k, t]) => [k, { stack: t.$value, css: ext(t).css ?? t.$value.join(", ") }]));
const durations = Object.entries(T.duration).map(([k, t]) => ({ k, ms: parseFloat(t.$value) }));
const easings = Object.entries(T.easing).map(([k, t]) => ({ k, v: t.$value }));
const shadowCss = (t) => t.$value.map((s) => `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color}`.replace(/(^| )0px/g, "$10")).join(", ");
const shadows = Object.entries(T.shadow).map(([k, t]) => ({ k, css: shadowCss(t) }));
const productText = new Set(["heading", "title", "metric", "display-sm", "display-md", "display-lg"]);

/* ---------- outputs ---------- */
const outputs = {};

outputs["css/variables.css"] = `/* ${HEADER}
 * Plain CSS variables: works with or without Tailwind.
 * Semantic colors switch with the .dark class on an ancestor (usually <html>). */
:root {
${primitives.map((p) => `  --${p.name}: ${p.oklch ?? p.hex};`).join("\n")}

  --radius: ${ext(T.radius.base).css};
${radius.filter((r) => r.k !== "base").map((r) => `  --rk-radius-${r.k}: ${r.css};`).join("\n")}
${spacing.map((s) => `  --rk-space-${s.k}: ${s.css};`).join("\n")}
${containers.map((c) => `  --rk-container-${c.k}: ${c.css};`).join("\n")}
${Object.entries(fonts).map(([k, f]) => `  --rk-font-${k}: ${f.css};`).join("\n")}
${text.map((t) => `  --rk-text-${t.k}: ${rem(t.size + "px")};`).join("\n")}
${durations.map((d) => `  --rk-duration-${d.k}: ${d.ms}ms;`).join("\n")}
${easings.map((e) => `  --rk-ease-${e.k}: cubic-bezier(${e.v.join(", ")});`).join("\n")}
${shadows.map((s) => `  --rk-shadow-${s.k}: ${s.css};`).join("\n")}
}

/* Semantic: light */
:root {
${semantic.map((s) => `  --${s.name}: ${cssRef(s.lightRef)};`).join("\n")}
}

/* Semantic: dark */
.dark {
${semantic.filter((s) => s.hasDark).map((s) => `  --${s.name}: ${cssRef(s.darkRef)};`).join("\n")}
}
`;

outputs["css/tailwind-theme.css"] = `/* ${HEADER}
 * Tailwind v4 scale (imported by theme.css). */
@theme inline {
${radius.filter((r) => !["base", "full"].includes(r.k)).map((r) => `  --radius-${r.k}: ${r.css};`).join("\n")}

${Object.entries(fonts).map(([k, f]) => `  --font-${k}: ${f.css};`).join("\n")}

${spacing.filter((s) => s.k !== "unit").map((s) => `  --spacing-${s.k}: ${s.css};`).join("\n")}
${containers.map((c) => `  --container-${c.k}: ${c.css};`).join("\n")}

${text.filter((t) => productText.has(t.k)).map((t) => [
  `  --text-${t.k}: ${rem(t.size + "px")};`,
  `  --text-${t.k}--line-height: ${t.lh};`,
  ...(t.ls ? [`  --text-${t.k}--letter-spacing: ${t.ls}em;`] : []),
].join("\n")).join("\n")}

${shadows.map((s) => `  --shadow-${s.k}: ${s.css};`).join("\n")}
${easings.map((e) => `  --ease-${e.k}: cubic-bezier(${e.v.join(", ")});`).join("\n")}
}
`;

const jsTokens = {
  color: {
    light: Object.fromEntries(semantic.map((s) => [camel(s.name), s.light])),
    dark: Object.fromEntries(semantic.map((s) => [camel(s.name), s.dark])),
  },
  primitive: Object.fromEntries(primitives.map((p) => [p.key, p.hex])),
  radius: Object.fromEntries(radius.map((r) => [r.k, r.px])),
  spacing: Object.fromEntries(spacing.map((s) => [camel(s.k), s.px])),
  container: Object.fromEntries(containers.map((c) => [c.k, c.px])),
  font: { sans: fonts.sans.stack, mono: fonts.mono.stack, weight: weights },
  text: Object.fromEntries(text.map((t) => [camel(t.k), { fontSize: t.size, lineHeight: t.lh, letterSpacing: t.ls }])),
  duration: Object.fromEntries(durations.map((d) => [d.k, d.ms])),
  easing: Object.fromEntries(easings.map((e) => [camel(e.k), e.v])),
  shadow: Object.fromEntries(shadows.map((s) => [s.k, s.css])),
};
outputs["js/tokens.mjs"] = `// ${HEADER}\nexport const tokens = ${JSON.stringify(jsTokens, null, 2)};\nexport default tokens;\n`;
outputs["js/tokens.cjs"] = `// ${HEADER}\nconst tokens = ${JSON.stringify(jsTokens, null, 2)};\nmodule.exports = tokens;\nmodule.exports.tokens = tokens;\nmodule.exports.default = tokens;\n`;
outputs["js/tokens.d.ts"] = `// ${HEADER}\nexport declare const tokens: ${JSON.stringify(jsTokens, null, 2)};\nexport default tokens;\n`;
outputs["json/tokens.json"] = JSON.stringify(jsTokens, null, 2) + "\n";

outputs["tailwind/preset.cjs"] = `// ${HEADER}
// Tailwind CSS v3 preset. Also import "@rekanica/tokens/variables.css" in your global CSS.
/** @type {import('tailwindcss').Config} */
module.exports = {
  darkMode: "class",
  theme: {
    extend: {
      colors: ${JSON.stringify(Object.fromEntries(semantic.map((s) => [s.name, `var(--${s.name})`])), null, 6).replace(/\n}/, "\n      }")},
      borderRadius: ${JSON.stringify(Object.fromEntries(radius.filter((r) => !["base", "full"].includes(r.k)).map((r) => [r.k, r.css])))},
      fontFamily: { sans: ${JSON.stringify(fonts.sans.stack)}, mono: ${JSON.stringify(fonts.mono.stack)} },
      spacing: ${JSON.stringify(Object.fromEntries(spacing.filter((s) => s.k !== "unit").map((s) => [s.k, s.css])))},
      maxWidth: ${JSON.stringify(Object.fromEntries(containers.map((c) => [c.k, c.css])))},
      fontSize: ${JSON.stringify(Object.fromEntries(text.filter((t) => productText.has(t.k)).map((t) => [t.k, [rem(t.size + "px"), { lineHeight: String(t.lh), ...(t.ls ? { letterSpacing: `${t.ls}em` } : {}) }]])))},
      boxShadow: ${JSON.stringify(Object.fromEntries(shadows.map((s) => [s.k, s.css])))},
      transitionTimingFunction: ${JSON.stringify(Object.fromEntries(easings.map((e) => [e.k, `cubic-bezier(${e.v.join(", ")})`])))},
    },
  },
};
`;

const argb = (hex) => `0xFF${hex.slice(1).toUpperCase()}`;
const weightName = { 300: "w300", 400: "w400", 500: "w500" };
const textWeight = (k) => (k === "metric" ? 300 : 400);

outputs["flutter/rekanica_tokens.dart"] = `// ${HEADER}
// Usage: MaterialApp(theme: rekanicaTheme(Brightness.light), darkTheme: rekanicaTheme(Brightness.dark))
import 'package:flutter/material.dart';

@immutable
class RekanicaColors {
  const RekanicaColors({
${semantic.map((s) => `    required this.${camel(s.name)},`).join("\n")}
  });
${semantic.map((s) => `  final Color ${camel(s.name)};`).join("\n")}

  static const light = RekanicaColors(
${semantic.map((s) => `    ${camel(s.name)}: Color(${argb(s.light)}),`).join("\n")}
  );
  static const dark = RekanicaColors(
${semantic.map((s) => `    ${camel(s.name)}: Color(${argb(s.dark)}),`).join("\n")}
  );
}

class RekanicaRadius {
${radius.map((r) => `  static const double ${camel(r.k === "2xl" ? "xxl" : r.k)} = ${r.px};`).join("\n")}
}

class RekanicaSpacing {
${spacing.map((s) => `  static const double ${camel(s.k)} = ${s.px};${s.desc ? ` // ${s.desc}` : ""}`).join("\n")}
}

class RekanicaText {
  static const String family = 'Geist';
  static const String monoFamily = 'Geist Mono';
${text.map((t) => `  static const TextStyle ${camel(t.k.replace(/^(\d)/, "x$1"))} = TextStyle(fontFamily: family, fontSize: ${t.size}, height: ${t.lh}, letterSpacing: ${+(t.ls * t.size).toFixed(2)}, fontWeight: FontWeight.${weightName[textWeight(t.k)]});`).join("\n")}
}

class RekanicaMotion {
${durations.map((d) => `  static const Duration ${d.k} = Duration(milliseconds: ${d.ms});`).join("\n")}
${easings.map((e) => `  static const Curve ${camel(e.k)} = Cubic(${e.v.join(", ")});`).join("\n")}
}

ThemeData rekanicaTheme(Brightness brightness) {
  final c = brightness == Brightness.dark ? RekanicaColors.dark : RekanicaColors.light;
  final pill = const StadiumBorder();
  return ThemeData(
    useMaterial3: true,
    brightness: brightness,
    fontFamily: RekanicaText.family,
    scaffoldBackgroundColor: c.background,
    dividerColor: c.border,
    colorScheme: ColorScheme(
      brightness: brightness,
      primary: c.primary, onPrimary: c.primaryForeground,
      secondary: c.secondary, onSecondary: c.secondaryForeground,
      error: c.destructive, onError: c.destructiveForeground,
      surface: c.card, onSurface: c.foreground,
      outline: c.border, surfaceContainerHighest: c.muted,
    ),
    cardTheme: CardThemeData(
      color: c.card, elevation: 0, margin: EdgeInsets.zero,
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(RekanicaRadius.xxl), side: BorderSide(color: c.border)),
    ),
    filledButtonTheme: FilledButtonThemeData(style: FilledButton.styleFrom(shape: pill, backgroundColor: c.primary, foregroundColor: c.primaryForeground)),
    outlinedButtonTheme: OutlinedButtonThemeData(style: OutlinedButton.styleFrom(shape: pill, side: BorderSide(color: c.border), foregroundColor: c.foreground)),
    inputDecorationTheme: InputDecorationTheme(
      border: OutlineInputBorder(borderRadius: BorderRadius.circular(RekanicaRadius.lg), borderSide: BorderSide(color: c.input)),
      enabledBorder: OutlineInputBorder(borderRadius: BorderRadius.circular(RekanicaRadius.lg), borderSide: BorderSide(color: c.input)),
      focusedBorder: OutlineInputBorder(borderRadius: BorderRadius.circular(RekanicaRadius.lg), borderSide: BorderSide(color: c.ring, width: 1.5)),
    ),
  );
}
`;

outputs["ios/RekanicaTokens.swift"] = `// ${HEADER}
// SwiftUI. Colors adapt to light/dark automatically.
import SwiftUI
import UIKit

public enum Rekanica {
    public enum Colors {
${semantic.map((s) => `        public static let ${camel(s.name)} = Color(light: ${s.light.replace("#", "0x")}, dark: ${s.dark.replace("#", "0x")})`).join("\n")}
    }
    public enum Radius {
${radius.map((r) => `        public static let ${camel(r.k === "2xl" ? "xxl" : r.k)}: CGFloat = ${r.px}`).join("\n")}
    }
    public enum Spacing {
${spacing.map((s) => `        public static let ${camel(s.k)}: CGFloat = ${s.px}`).join("\n")}
    }
    public enum Typography {
${text.map((t) => `        public static let ${camel(t.k.replace(/^(\d)/, "x$1"))} = Font.custom("Geist", size: ${t.size}).weight(.${textWeight(t.k) === 300 ? "light" : "regular"})`).join("\n")}
    }
    public enum Motion {
${durations.map((d) => `        public static let ${d.k}: Double = ${d.ms / 1000}`).join("\n")}
${easings.map((e) => `        public static let ${camel(e.k)} = Animation.timingCurve(${e.v.join(", ")}, duration: ${durations.find((d) => d.k === "slow").ms / 1000})`).join("\n")}
    }
}

extension Color {
    init(light: UInt32, dark: UInt32) {
        func ui(_ hex: UInt32) -> UIColor {
            UIColor(red: CGFloat((hex >> 16) & 0xFF) / 255, green: CGFloat((hex >> 8) & 0xFF) / 255, blue: CGFloat(hex & 0xFF) / 255, alpha: 1)
        }
        self.init(uiColor: UIColor { $0.userInterfaceStyle == .dark ? ui(dark) : ui(light) })
    }
}
`;

outputs["android/RekanicaTokens.kt"] = `// ${HEADER}
// Jetpack Compose. Usage: MaterialTheme(colorScheme = rekanicaColorScheme(isSystemInDarkTheme())) { … }
package com.aturanica.rekanica

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

object RekanicaColors {
    object Light {
${semantic.map((s) => `        val ${pascal(s.name)} = Color(${argb(s.light)})`).join("\n")}
    }
    object Dark {
${semantic.map((s) => `        val ${pascal(s.name)} = Color(${argb(s.dark)})`).join("\n")}
    }
}

object RekanicaRadius {
${radius.map((r) => `    val ${pascal(r.k === "2xl" ? "xxl" : r.k)} = ${r.px}.dp`).join("\n")}
}

object RekanicaSpacing {
${spacing.map((s) => `    val ${pascal(s.k)} = ${s.px}.dp`).join("\n")}
}

object RekanicaTextSize {
${text.map((t) => `    val ${pascal(t.k.replace(/^(\d)/, "x$1"))} = ${t.size}.sp`).join("\n")}
}

fun rekanicaColorScheme(dark: Boolean): ColorScheme = if (dark) {
    darkColorScheme(
        primary = RekanicaColors.Dark.Primary, onPrimary = RekanicaColors.Dark.PrimaryForeground,
        secondary = RekanicaColors.Dark.Secondary, onSecondary = RekanicaColors.Dark.SecondaryForeground,
        background = RekanicaColors.Dark.Background, onBackground = RekanicaColors.Dark.Foreground,
        surface = RekanicaColors.Dark.Card, onSurface = RekanicaColors.Dark.Foreground,
        error = RekanicaColors.Dark.Destructive, onError = RekanicaColors.Dark.DestructiveForeground,
        outline = RekanicaColors.Dark.Border,
    )
} else {
    lightColorScheme(
        primary = RekanicaColors.Light.Primary, onPrimary = RekanicaColors.Light.PrimaryForeground,
        secondary = RekanicaColors.Light.Secondary, onSecondary = RekanicaColors.Light.SecondaryForeground,
        background = RekanicaColors.Light.Background, onBackground = RekanicaColors.Light.Foreground,
        surface = RekanicaColors.Light.Card, onSurface = RekanicaColors.Light.Foreground,
        error = RekanicaColors.Light.Destructive, onError = RekanicaColors.Light.DestructiveForeground,
        outline = RekanicaColors.Light.Border,
    )
}
`;

outputs["figma/tokens-studio.json"] = JSON.stringify({
  primitive: { rk: T.rk },
  light: { color: Object.fromEntries(semantic.map((s) => [s.name, { $type: "color", $value: s.lightRef }])) },
  dark: { color: Object.fromEntries(semantic.map((s) => [s.name, { $type: "color", $value: s.darkRef }])) },
  dimension: { radius: T.radius, spacing: T.spacing, container: T.container },
  $themes: [
    { id: "light", name: "Light", selectedTokenSets: { primitive: "source", dimension: "source", light: "enabled" } },
    { id: "dark", name: "Dark", selectedTokenSets: { primitive: "source", dimension: "source", dark: "enabled" } },
  ],
  $metadata: { tokenSetOrder: ["primitive", "dimension", "light", "dark"] },
}, null, 2) + "\n";

/* ---------- write / check ---------- */
let stale = [];
for (const [rel, content] of Object.entries(outputs)) {
  const file = join(out, rel);
  if (CHECK) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== content) stale.push(rel);
    continue;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
}
if (CHECK && stale.length) {
  console.error(`Tokens out of date. Run: pnpm --filter @rekanica/tokens build\n  ${stale.join("\n  ")}`);
  process.exit(1);
}
console.log(`${CHECK ? "checked" : "built"} ${Object.keys(outputs).length} outputs · ${primitives.length} primitives · ${semantic.length} semantic colors`);
