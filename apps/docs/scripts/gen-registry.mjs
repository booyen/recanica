// Generates __registry__/index.tsx (lazy component maps) and registry.json
// (shadcn registry for patterns + blocks) from lib/catalog.json.
// Run: pnpm gen   (also runs before dev/build)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const catalog = JSON.parse(readFileSync(join(root, "lib/catalog.json"), "utf8"));

const missing = [];
const map = (items, file) =>
  items
    .map((i) => {
      const path = file(i.slug);
      if (!existsSync(join(root, path + ".tsx"))) missing.push(path);
      return `  "${i.slug}": dynamic(() => import("@/${path}")),`;
    })
    .join("\n");

const index = `// AUTO-GENERATED by scripts/gen-registry.mjs. Do not edit.
import dynamic from "next/dynamic";
import type { ComponentType } from "react";

export const examples: Record<string, ComponentType> = {
${map(catalog.components, (s) => `examples/${s}-demo`)}
};

export const patterns: Record<string, ComponentType> = {
${map(catalog.patterns, (s) => `registry/patterns/${s}`)}
};

export const blocks: Record<string, ComponentType> = {
${map(catalog.blocks, (s) => `registry/blocks/${s}`)}
};

export const web: Record<string, ComponentType> = {
${map(catalog.web, (s) => `registry/web/${s}`)}
};
`;
writeFileSync(join(root, "__registry__/index.tsx"), index);

const item = (kind, type) => (i) => ({
  name: i.slug,
  type,
  title: i.title,
  description: i.description,
  categories: [i.category.toLowerCase()],
  dependencies: ["@recanica/ui", "lucide-react"],
  files: [{ path: `registry/${kind}/${i.slug}.tsx`, type, target: `components/${kind}/${i.slug}.tsx` }],
});

const registry = {
  $schema: "https://ui.shadcn.com/schema/registry.json",
  name: "recanica",
  homepage: "https://recanica.aturanica.com",
  items: [
    ...catalog.patterns.map(item("patterns", "registry:block")),
    ...catalog.blocks.map(item("blocks", "registry:block")),
    ...catalog.web.map(item("web", "registry:block")),
  ],
};
writeFileSync(join(root, "registry.json"), JSON.stringify(registry, null, 2) + "\n");

if (missing.length) {
  console.warn(`gen-registry: ${missing.length} missing file(s):\n  ` + missing.join("\n  "));
  process.exitCode = 1;
} else {
  console.log(`gen-registry: ${catalog.components.length} components, ${catalog.patterns.length} patterns, ${catalog.blocks.length} blocks, ${catalog.web.length} web sections`);
}
